    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        String nombre = jTextField1.getText().trim();
        String tel = jTextField2.getText().trim();
        String dir = jTextArea1.getText().trim();

        if (nombre.isEmpty() || tel.isEmpty() || dir.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Llena los datos nuevos en el formulario antes de actualizar.", "Aviso", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        String idStr = javax.swing.JOptionPane.showInputDialog(this, "Ingresa el ID_Cl del cliente a actualizar:");
        if (idStr == null || idStr.trim().isEmpty()) return;

        try {
            int idCliente = Integer.parseInt(idStr.trim());
            if (base.consultas.updateCliente(idCliente, nombre, tel, dir)) {
                javax.swing.JOptionPane.showMessageDialog(this, "Cliente actualizado correctamente.");
                jTextField1.setText("");
                jTextField2.setText("");
                jTextArea1.setText("");
                base.refrescarTablaActual();
            }
        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "El ID debe ser un número entero.", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButton3ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        String nombre = jTextField1.getText().trim();
        String tel = jTextField2.getText().trim();
        String dir = jTextArea1.getText().trim();

        if (nombre.isEmpty() || tel.isEmpty() || dir.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Completa todos los campos del cliente.", "Aviso", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        if (base.consultas.insertCliente(nombre, tel, dir)) {
            javax.swing.JOptionPane.showMessageDialog(this, "Cliente registrado correctamente.");
            jTextField1.setText("");
            jTextField2.setText("");
            jTextArea1.setText("");
            base.refrescarTablaActual();
        }
    }//GEN-LAST:event_jButton2ActionPerformed


