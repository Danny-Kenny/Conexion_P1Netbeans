    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        String nombre = jTextField1.getText().trim();
        String precioStr = jTextField2.getText().trim();

        if (nombre.isEmpty() || precioStr.isEmpty() || jDateChooser1.getDate() == null) {
            javax.swing.JOptionPane.showMessageDialog(this, "Completa Nombre, Precio y Fecha de Caducidad.", "Aviso", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            double precio = Double.parseDouble(precioStr);
            
            // NOTA: Si en MySQL Fecha_Cad sigue como TIME usa "HH:mm:ss". 
            // Si lo cambias a DATE en MySQL, cambia el patrón a "yyyy-MM-dd"
            java.text.SimpleDateFormat sdf = new java.text.SimpleDateFormat("yyyy-MM-dd");
            String fechaCaducidad = sdf.format(jDateChooser1.getDate());

            boolean exito = base.consultas.insertProducto(nombre, precio, fechaCaducidad);
            if (exito) {
                javax.swing.JOptionPane.showMessageDialog(this, "Producto registrado correctamente.");
                jTextField1.setText("");
                jTextField2.setText("");
                jDateChooser1.setDate(null);
                base.refrescarTablaActual();
            }
        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "El precio debe ser un valor numérico válido.", "Error de formato", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButton2ActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        String nombre = jTextField1.getText().trim();
        String precioStr = jTextField2.getText().trim();

        if (nombre.isEmpty() || precioStr.isEmpty() || jDateChooser1.getDate() == null) {
            javax.swing.JOptionPane.showMessageDialog(this, "Llena todos los campos del producto antes de actualizar.", "Aviso", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        String idStr = javax.swing.JOptionPane.showInputDialog(this, "Ingresa el ID_Pr del producto a actualizar:");
        if (idStr == null || idStr.trim().isEmpty()) return;

        try {
            int idProducto = Integer.parseInt(idStr.trim());
            double precio = Double.parseDouble(precioStr);
            String estatus = jComboBox1.getSelectedItem().toString();

            java.text.SimpleDateFormat sdf = new java.text.SimpleDateFormat("yyyy-MM-dd");
            String fechaCaducidad = sdf.format(jDateChooser1.getDate());

            boolean exito = base.consultas.updateProducto(idProducto, nombre, precio, fechaCaducidad, estatus);
            if (exito) {
                javax.swing.JOptionPane.showMessageDialog(this, "Producto actualizado correctamente.");
                jTextField1.setText("");
                jTextField2.setText("");
                jDateChooser1.setDate(null);
                base.refrescarTablaActual();
            }
        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Verifica que tanto el ID como el Precio sean números válidos.", "Error de formato", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButton3ActionPerformed


