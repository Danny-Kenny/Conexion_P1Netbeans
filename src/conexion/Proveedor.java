    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        String nombre = jTextField1.getText().trim();
        if (nombre.isEmpty() || jComboBox2.getSelectedItem() == null) {
            javax.swing.JOptionPane.showMessageDialog(this, "Completa el nombre y selecciona un producto.", "Aviso", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        String seleccionado = jComboBox2.getSelectedItem().toString();
        int idProducto = Integer.parseInt(seleccionado.split(" - ")[0]);

        boolean exito = base.consultas.insertProveedor(nombre, idProducto);
        if (exito) {
            javax.swing.JOptionPane.showMessageDialog(this, "Proveedor registrado correctamente.");
            jTextField1.setText("");
            base.refrescarTablaActual();
        }
    }//GEN-LAST:event_jButton2ActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        String nombre = jTextField1.getText().trim();
        if (nombre.isEmpty() || jComboBox2.getSelectedItem() == null) {
            javax.swing.JOptionPane.showMessageDialog(this, "Llena los datos nuevos en el formulario antes de actualizar.", "Aviso", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        String idStr = javax.swing.JOptionPane.showInputDialog(this, "Ingresa el ID_Prov del proveedor a actualizar:");
        if (idStr == null || idStr.trim().isEmpty()) return;

        try {
            int idProveedor = Integer.parseInt(idStr.trim());
            String estatus = jComboBox1.getSelectedItem().toString();
            String seleccionado = jComboBox2.getSelectedItem().toString();
            int idProducto = Integer.parseInt(seleccionado.split(" - ")[0]);

            boolean exito = base.consultas.updateProveedor(idProveedor, nombre, estatus, idProducto);
            if (exito) {
                javax.swing.JOptionPane.showMessageDialog(this, "Proveedor actualizado correctamente.");
                jTextField1.setText("");
                base.refrescarTablaActual();
            }
        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "El ID del proveedor debe ser un número.", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButton3ActionPerformed

