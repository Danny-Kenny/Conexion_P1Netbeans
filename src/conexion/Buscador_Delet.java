    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String idStr = jTextField5.getText().trim();
        if (idStr.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Escribe un ID o Folio para eliminar.");
            return;
        }

        try {
            int id = Integer.parseInt(idStr);
            int confirmar = javax.swing.JOptionPane.showConfirmDialog(this, "¿Seguro que deseas eliminar el registro #" + id + "?", "Confirmar", javax.swing.JOptionPane.YES_NO_OPTION);
            if (confirmar == javax.swing.JOptionPane.YES_OPTION) {
                if (base.eliminarPorId(id)) {
                    javax.swing.JOptionPane.showMessageDialog(this, "Registro eliminado.");
                    jTextField5.setText("");
                }
            }
        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "El ID debe ser un número entero.");
        }
    }//GEN-LAST:event_jButton1ActionPerformed


