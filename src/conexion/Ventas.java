    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        if (idProductoSeleccionado == -1) {
            javax.swing.JOptionPane.showMessageDialog(this, "Por favor, selecciona un producto de la tabla.", "Aviso", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        String textoCliente = jTextField3.getText().trim();
        if (textoCliente.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Ingresa el ID / Membresía del cliente.", "Aviso", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            int idCliente = Integer.parseInt(textoCliente);
            int cantidad = (int) jSpinner1.getValue();

            if (cantidad <= 0) {
                javax.swing.JOptionPane.showMessageDialog(this, "La cantidad debe ser mayor a 0.", "Aviso", javax.swing.JOptionPane.WARNING_MESSAGE);
                return;
            }

            String nombreProducto = jTextField1.getText();
            double totalVenta = precioUnitario * cantidad;

            // Insertamos y obtenemos el Folio real de la BD
            int folioGenerado = base.consultas.insertVenta(totalVenta, idProductoSeleccionado, idCliente);

            if (folioGenerado != -1) {
                // Construimos el diseño del ticket para el JOptionPane
                String ticket = "==============================\n"
                              + "         TICKET DE VENTA      \n"
                              + "==============================\n"
                              + "Folio: #" + folioGenerado + "\n"
                              + "Cliente ID: " + idCliente + "\n"
                              + "------------------------------\n"
                              + "Producto: " + nombreProducto + "\n"
                              + "Precio Unitario: $" + String.format("%.2f", precioUnitario) + "\n"
                              + "Cantidad: " + cantidad + "\n"
                              + "------------------------------\n"
                              + "TOTAL A PAGAR: $" + String.format("%.2f", totalVenta) + "\n"
                              + "==============================";

                javax.swing.JOptionPane.showMessageDialog(this, ticket, "Comprobante de Venta", javax.swing.JOptionPane.INFORMATION_MESSAGE);

                // Limpiar campos para la siguiente venta
                idProductoSeleccionado = -1;
                precioUnitario = 0.0;
                jTextField1.setText("");
                jTextField2.setText("");
                jTextField3.setText("");
                jSpinner1.setValue(0);

                base.refrescarTablaActual();
            }

        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "La membresía del cliente debe ser un número entero válido.", "Error de formato", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButton1ActionPerformed

