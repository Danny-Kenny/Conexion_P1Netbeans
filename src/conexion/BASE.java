    public void mostrarPanel(JPanel contenedor, JPanel contenido) {
        contenido.setSize(contenedor.getWidth(), contenedor.getHeight());
        contenido.setLocation(0, 0);
        contenedor.removeAll();
        contenedor.setLayout(new BorderLayout());
        contenedor.add(contenido, BorderLayout.CENTER);
        contenedor.revalidate();
        contenedor.repaint();
    }
    
    private void cambiarModulo(String nombreModulo, JPanel formulario) {
        this.moduloActual = nombreModulo;
        
        if (nombreModulo.equals("Ventas")) {
            this.panelVentasActual = (Ventas) formulario;
        } else {
            this.panelVentasActual = null;
        }
        
        refrescarTablaActual();
        mostrarPanel(jPanel1, formulario); 
    }
    
    public void refrescarTablaActual() {
        switch (moduloActual) {
            case "Clientes":
                jTable1.setModel(consultas.mostrarClientes(""));
                break;
            case "Ventas":
                // En ventas mostramos por defecto los productos disponibles para poder seleccionarlos
                jTable1.setModel(consultas.mostrarProductosParaVenta());
                break;
            case "Producto":
                jTable1.setModel(consultas.mostrarProductos(""));
                break;
            case "Proveedor":
                jTable1.setModel(consultas.mostrarProveedores(""));
                break;
        }
    }
    
    public void buscarPorId(String id) {
        if (id == null || id.trim().isEmpty()) {
            refrescarTablaActual();
            return;
        }
        switch (moduloActual) {
            case "Clientes":
                jTable1.setModel(consultas.mostrarClientes(id));
                break;
            case "Ventas":
                // Busca el Folio en la tabla Ventas
                jTable1.setModel(consultas.mostrarVentas(id));
                break;
            case "Producto":
                jTable1.setModel(consultas.mostrarProductos(id));
                break;
            case "Proveedor":
                jTable1.setModel(consultas.mostrarProveedores(id));
                break;
        }
    }

    public boolean eliminarPorId(int id) {
        boolean exito = false;
        switch (moduloActual) {
            case "Clientes":
                exito = consultas.deleteCliente(id);
                break;
            case "Ventas":
                exito = consultas.deleteVenta(id);
                break;
            case "Producto":
                exito = consultas.deleteProducto(id);
                break;
            case "Proveedor":
                exito = consultas.deleteProveedor(id);
                break;
        }
        if (exito) {
            refrescarTablaActual();
        }
        return exito;
    }
    
    
