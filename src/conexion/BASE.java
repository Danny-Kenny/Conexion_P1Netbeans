    private void jTable1MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTable1MouseClicked
        int fila = jTable1.getSelectedRow();
        
        // Si estamos en Ventas y se seleccionó una fila del catálogo de productos:
        if (fila >= 0 && moduloActual.equals("Ventas") && panelVentasActual != null) {
            // Validamos que la tabla actual sea la de productos (4 columnas: ID, Nombre, Precio, Estatus)
            if (jTable1.getColumnCount() == 4) {
                int idProd = Integer.parseInt(jTable1.getValueAt(fila, 0).toString());
                String nombre = jTable1.getValueAt(fila, 1).toString();
                double precio = Double.parseDouble(jTable1.getValueAt(fila, 2).toString());
                
                panelVentasActual.cargarProductoSeleccionado(idProd, nombre, precio);
            }
        }
    }//GEN-LAST:event_jTable1MouseClicked

